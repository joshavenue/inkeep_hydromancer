import fs from 'node:fs';
import assert from 'node:assert/strict';
const cfg = JSON.parse(fs.readFileSync('preview-client.json', 'utf8'));
const state = JSON.parse(fs.readFileSync('../frontend/state.json', 'utf8'));
const hostname = new URL(state.publishedOrigin).hostname;
assert.ok(hostname.endsWith('.trycloudflare.com'));
const logDir = new URL('./logs/', import.meta.url);
fs.mkdirSync(logDir, { recursive: true, mode: 0o700 });
const headers = { Authorization: `Bearer ${process.env.INKEEP_AGENTS_MANAGE_API_BYPASS_SECRET}`, 'Content-Type': 'application/json' };
const beforeResponse = await fetch(cfg.manageAppUrl, { headers });
assert.equal(beforeResponse.status, 200);
const before = await beforeResponse.json();
const app = before.data;
assert.equal(app.id, cfg.appId);
const allowedDomains = [...new Set([...(app.config?.webClient?.allowedDomains ?? []), hostname])];
const config = { ...app.config, type: 'web_client', webClient: { ...app.config.webClient, allowedDomains, allowAnonymous: true } };
const changed = await fetch(cfg.manageAppUrl, { method: 'PATCH', headers, body: JSON.stringify({ config }) });
assert.ok(changed.ok, `App update status ${changed.status}`);
const afterResponse = await fetch(cfg.manageAppUrl, { headers });
assert.equal(afterResponse.status, 200);
const after = (await afterResponse.json()).data;
assert.ok(after.config.webClient.allowedDomains.includes(hostname));
assert.equal(after.config.webClient.allowAnonymous, true);
fs.writeFileSync('preview-client.json', JSON.stringify({ ...cfg, allowedDomains: after.config.webClient.allowedDomains }, null, 2), { mode: 0o600 });
const receipt = { appId: after.id, allowedDomains: after.config.webClient.allowedDomains, allowAnonymous: after.config.webClient.allowAnonymous, readbackStatus: afterResponse.status };
fs.writeFileSync(new URL('public-app-verification.json', logDir), JSON.stringify(receipt, null, 2));
console.log(JSON.stringify(receipt));
